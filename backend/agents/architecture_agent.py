import json
import logging
from typing import Dict, Any
from backend.models.schemas import ProjectState
from backend.services.llm_service import call_llm_structured

logger = logging.getLogger("ArchitectureAgent")

AGENT_ROLE = "System Architect"
AGENT_GOAL = "Design an appropriate high-level architecture based on the project requirements generated by the Requirement Agent."

def run_architecture_agent(state: ProjectState) -> ProjectState:
    """Agent 2: System Architect"""
    project_idea = state.get("project_idea", "")
    requirements = state.get("requirements", {})
    api_key = state.get("api_key")
    
    input_context = f"Project Requirements:\n{json.dumps(requirements, indent=2)}"
    
    user_prompt = f"""
ROLE: {AGENT_ROLE}
GOAL: {AGENT_GOAL}
INPUT:
Raw Idea: {project_idea}
Project Requirements Context:
{json.dumps(requirements, indent=2)}

REASONING TASK:
1. Review the requirements provided by the Requirement Agent.
2. Determine an appropriate architecture style (e.g. Client-Server Monolith, Modular Architecture) suitable for a student/academic software project.
3. Identify major system components (Frontend UI, Backend Application, Database, AI Engine, etc.) and define specific responsibilities for each.
4. Outline step-by-step data flow across components.
5. Write a concise architecture description explaining why this design fits the project.
6. Avoid unnecessary microservice or complex distributed infrastructure complexity.

OUTPUT FORMAT:
Return a JSON object with:
{{
  "architecture_style": "Style name",
  "components": [
    {{ "name": "Component Name", "responsibility": "Component responsibility description" }}
  ],
  "data_flow": ["Step 1 description", "Step 2 description"],
  "architecture_description": "Narrative architecture explanation"
}}
"""
    logger.info("Executing Architecture Agent...")
    output = call_llm_structured(
        system_role=f"You are a Lead {AGENT_ROLE}. Design practical, high-level software architectures for student projects.",
        user_prompt=user_prompt,
        output_schema_name="ArchitectureOutput",
        api_key=api_key
    )

    log_entry = {
        "agent_id": "agent_2",
        "agent_name": "Architecture Agent",
        "role": AGENT_ROLE,
        "goal": AGENT_GOAL,
        "input_context": input_context,
        "prompt": user_prompt.strip(),
        "output": output,
        "status": "completed"
    }

    logs = state.get("agent_logs", [])
    logs.append(log_entry)

    state["architecture"] = output
    state["agent_logs"] = logs
    state["current_agent"] = "Architecture Agent"
    return state
